# audio_describer/ui/export_options_dialog.py
import wx
from ..i18n_setup import _


class ExportOptionsDialog(wx.Dialog):
    def __init__(self, parent, extended_default=False):
        super().__init__(parent, title=_("Export Options"), style=wx.DEFAULT_DIALOG_STYLE)

        main_sizer = wx.BoxSizer(wx.VERTICAL)
        panel = wx.Panel(self)
        panel_sizer = wx.BoxSizer(wx.VERTICAL)

        # (format key, category, label)
        self.export_choices_map = [
            ("mkv_ad", "av", _("Video with a separate audio description track (MKV, original tracks kept)")),
            ("mp4_ad", "av", _("Video with a separate audio description track (MP4, for most players and phones)")),
            ("mp3_ducked", "av", _("MP3 Audio (Descriptions mixed with original video)")),
            ("ad_only", "av", _("Audio description track only (M4A)")),
            ("vtt", "text", _("WebVTT descriptions (.vtt, for web players and platforms)")),
            ("srt", "text", _("SRT Subtitle File (Descriptions as subtitles)")),
            ("txt_line", "text", _("Plain Text File (.txt) (Descriptions line-by-line)")),
            ("dapt", "text", _("Audio description script, W3C TTML DAPT (.ttml, for professional tools)")),
            ("docx", "text", _("Production script for review (Word .docx: timecodes, text, status, notes)")),
            ("full_script", "full", _("Full script: transcribed dialogue and descriptions (.txt, for deafblind readers; uses the AI)")),
        ]

        self.export_radiobox = wx.RadioBox(
            panel,
            label=_("Select Export Format"),
            choices=[item[2] for item in self.export_choices_map],
            majorDimension=1,
            style=wx.RA_SPECIFY_COLS
        )
        self.export_radiobox.SetSelection(0)
        panel_sizer.Add(self.export_radiobox, 0, wx.EXPAND | wx.ALL, 10)

        self.density_checkbox = wx.CheckBox(panel, label=_("Only the descriptions of the current &density, as heard in the player"))
        self.density_checkbox.SetValue(True)
        self.extended_checkbox = wx.CheckBox(panel, label=_(
            "E&xtended description: pause the picture when a description is longer than its pause (the video is re-encoded)"))
        self.extended_checkbox.SetValue(bool(extended_default))
        self.credit_checkbox = wx.CheckBox(panel, label=_("Add a spoken c&redit at the end: audio description generated by AI"))
        self.credit_checkbox.SetValue(True)
        for box in (self.density_checkbox, self.extended_checkbox, self.credit_checkbox):
            panel_sizer.Add(box, 0, wx.LEFT | wx.RIGHT | wx.BOTTOM, 10)
        self.export_radiobox.Bind(wx.EVT_RADIOBOX, lambda e: self._update_options())
        self._update_options()

        panel.SetSizer(panel_sizer)
        main_sizer.Add(panel, 1, wx.EXPAND)

        button_sizer = self.CreateStdDialogButtonSizer(wx.OK | wx.CANCEL)
        ok_button = self.FindWindowById(wx.ID_OK)
        ok_button.SetLabel(_("&Continue"))
        ok_button.SetDefault()

        main_sizer.Add(button_sizer, 0, wx.ALIGN_CENTER | wx.ALL, 10)
        self.SetSizerAndFit(main_sizer)
        self.CentreOnParent()

    def _update_options(self):
        format_key, category, _label = self.export_choices_map[self.export_radiobox.GetSelection()]
        self.extended_checkbox.Enable(format_key in ("mkv_ad", "mp4_ad", "mp3_ducked"))
        self.credit_checkbox.Enable(category == "av")

    def GetValues(self):
        format_key, category, _label = self.export_choices_map[self.export_radiobox.GetSelection()]
        return {"category": category, "format": format_key,
                "current_density": self.density_checkbox.GetValue(),
                "extended": self.extended_checkbox.IsEnabled() and self.extended_checkbox.GetValue(),
                "credit": self.credit_checkbox.IsEnabled() and self.credit_checkbox.GetValue()}
